def write_pptx(output: Path) -> None:
    slides = build_slides()
    with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as deck:
        deck.writestr("[Content_Types].xml", content_types(len(slides)))
        deck.writestr("_rels/.rels", rels_xml())
        deck.writestr("docProps/core.xml", core_xml())
        deck.writestr("docProps/app.xml", app_xml(len(slides)))
        deck.writestr("ppt/presentation.xml", presentation_xml(len(slides)))
        deck.writestr("ppt/_rels/presentation.xml.rels", presentation_rels(len(slides)))
        deck.writestr("ppt/slideMasters/slideMaster1.xml", slide_master_xml())
        deck.writestr("ppt/slideMasters/_rels/slideMaster1.xml.rels", slide_master_rels())
        deck.writestr("ppt/slideLayouts/slideLayout1.xml", slide_layout_xml())
        deck.writestr("ppt/slideLayouts/_rels/slideLayout1.xml.rels", slide_layout_rels())
        deck.writestr("ppt/theme/theme1.xml", theme_xml())
        for i, slide in enumerate(slides, 1):
            deck.writestr(f"ppt/slides/slide{i}.xml", slide)
            deck.writestr(f"ppt/slides/_rels/slide{i}.xml.rels", slide_rels())


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    output = root / "docs" / "Nabda_Multilingual_NLP_Medical_Assistant_Draft_CLEAN.pptx"
    write_pptx(output)
    print(output)


if __name__ == "__main__":
    main()
